export function getInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'ja';
  }

  const storedLocale = localStorage.getItem(UI_LOCALE_KEY);
  return storedLocale === 'en' || storedLocale === 'ja' ? storedLocale : 'ja';
}

